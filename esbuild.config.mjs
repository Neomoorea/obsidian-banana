import esbuild from 'esbuild'
import { copy } from 'esbuild-plugin-copy'
import esbuildSvelte from 'esbuild-svelte'
import { builtinModules } from 'node:module'
import path from 'path'
import { mkdirSync, rmSync } from 'node:fs'
import process from 'process'
import { sveltePreprocess } from 'svelte-preprocess'

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`

const prod = process.argv[2] === 'production'
const outputDir = './dist'
// dist contains generated plugin files only; remove stale nested output or docs
// left behind by older builds before generating the new root-level bundle.
rmSync(outputDir, { recursive: true, force: true })
mkdirSync(outputDir, { recursive: true })

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['./src/main.ts'],
  bundle: true,
  // Replace this expression at build time; Node's process global isn't
  // guaranteed to exist in Obsidian's renderer.
  define: { 'process.env.NODE_ENV': prod ? '"production"' : '"development"' },
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  outfile: path.join(outputDir, 'main.js'),
  plugins: [
    esbuildSvelte({
      compilerOptions: { css: 'injected' },
      preprocess: sveltePreprocess(),
    }),
    copy({
      assets: {
        from: ['manifest.json', './assets/styles.css'],
        to: [outputDir],
      },
    }),
  ],
  format: 'cjs',
  target: 'chrome98',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  minify: prod,
})

if (prod) {
  await context.rebuild()
  process.exit(0)
} else {
  await context.watch()
}
